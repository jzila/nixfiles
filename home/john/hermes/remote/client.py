"""`hermes` where Hermes is remote (../default.nix). `login`: the dashboard's native-app sign-in
(RFC 8252, through its OIDC provider) with a loopback redirect; the tokens go to a 0600 file and are
refreshed when near expiry or rejected. `ticket`: a single-use WebSocket ticket. The API's commands
(hermes_api.py, generated by gen.py) and `kanban` (kanban.py) call the dashboard; anything else
starts the TUI attached to it.
"""

import argparse
import base64
import hashlib
import http.server
import json
import mimetypes
import os
import secrets
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import webbrowser
from pathlib import Path

import hermes_api
import kanban

BASE = os.environ.get("HERMES_REMOTE_URL", "")
STATE = Path(os.environ.get("HERMES_REMOTE_STATE", "."))
TOKENS = STATE / "tokens.json"


def request(method, path, query=None, body=None, bearer=None):
    """`body` is a dict sent as JSON, or (bytes, content type)."""
    data, ctype = (json.dumps(body).encode(), "application/json") if isinstance(body, dict) else body or (None, None)
    headers = {k: v for k, v in (("Content-Type", ctype), ("Authorization", bearer and f"Bearer {bearer}")) if v}
    url = BASE + path + ("?" + urllib.parse.urlencode(query, doseq=True) if query else "")
    with urllib.request.urlopen(urllib.request.Request(url, data, headers, method=method), timeout=60) as r:
        raw = r.read()
        return json.loads(raw) if r.headers.get_content_type() == "application/json" else raw


def save(tokens):
    TOKENS.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    fd = os.open(TOKENS, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        json.dump(tokens, f)


def login(_=None):
    verifier = secrets.token_urlsafe(48)
    challenge = base64.urlsafe_b64encode(hashlib.sha256(verifier.encode()).digest()).rstrip(b"=").decode()
    state = secrets.token_urlsafe(16)
    reply = {}

    class Callback(http.server.BaseHTTPRequestHandler):
        def do_GET(self):
            reply.update(urllib.parse.parse_qsl(urllib.parse.urlsplit(self.path).query))
            self.send_response(200)
            self.end_headers()
            self.wfile.write(b"Signed in to Hermes; you can close this tab.")

        def log_message(self, *_):
            pass

    server = http.server.HTTPServer(("127.0.0.1", 0), Callback)
    url = BASE + "/auth/native/authorize?" + urllib.parse.urlencode({
        "provider": "self-hosted", "code_challenge": challenge, "code_challenge_method": "S256",
        "redirect_uri": f"http://127.0.0.1:{server.server_port}/callback", "state": state})
    print(f"Sign in at {url}", file=sys.stderr)
    webbrowser.open(url)
    while not reply:
        server.handle_request()
    if reply.get("state") != state or "code" not in reply:
        sys.exit(f"Sign-in failed: {reply.get('error', 'no code')}")
    save(request("POST", "/auth/native/token", body={"code": reply["code"], "code_verifier": verifier}))
    print("Signed in.", file=sys.stderr)


def refresh(tokens):
    tokens = request("POST", "/auth/native/refresh",
                     body={"refresh_token": tokens["refresh_token"], "provider": tokens["provider"]})
    save(tokens)
    return tokens


def call(method, path, query=None, body=None):
    try:
        tokens = json.loads(TOKENS.read_text())
    except FileNotFoundError:
        sys.exit("Not signed in: run `hermes login`.")
    try:
        if tokens["expires_at"] < time.time() + 60:
            tokens = refresh(tokens)
        try:
            return request(method, path, query, body, tokens["access_token"])
        except urllib.error.HTTPError as e:
            if e.code != 401:
                raise
            return request(method, path, query, body, refresh(tokens)["access_token"])
    except urllib.error.HTTPError as e:
        sys.exit("Session expired: run `hermes login`." if e.code == 401
                 else f"Hermes: HTTP {e.code}: {e.read().decode(errors='replace')[:2000]}")


def multipart(fields):
    """`fields`: (name, value), a file's value being (filename, content type, bytes)."""
    boundary, out = secrets.token_hex(16), b""
    for name, value in fields:
        head = f'--{boundary}\r\nContent-Disposition: form-data; name="{name}"'
        if isinstance(value, tuple):
            filename, ctype, value = value
            head += f'; filename="{filename}"\r\nContent-Type: {ctype or mimetypes.guess_type(filename)[0] or "application/octet-stream"}'
        out += f"{head}\r\n\r\n".encode() + (value if isinstance(value, bytes) else str(value).encode()) + b"\r\n"
    return out + f"--{boundary}--\r\n".encode(), f"multipart/form-data; boundary={boundary}"


def run(key, /, **values):
    """Call the generated operation `key` with the values given for its arguments."""
    op = hermes_api.COMMANDS[key]
    path, query, body = op["path"], {}, {}
    for name, where, kind, _, _ in op["args"]:
        if (value := values.get(name)) is None:
            continue
        if where == "path":
            path = path.replace(f"{{{name}}}", urllib.parse.quote(str(value), safe=""))
        elif where == "query":
            query[name] = json.dumps(value) if isinstance(value, bool) else value
        else:
            body[name] = value
    return call(op["method"], path, query, multipart(body.items()) if op["body"] == "form" else body if op["body"] else None)


def upload(path):
    return Path(path).name, None, Path(path).read_bytes()


TYPES = {"int": int, "float": float, "json": json.loads, "file": upload}


def add_commands(sub, keys, skip=0):
    """One subcommand per generated operation, nested by its words (after the first `skip`)."""
    groups = {(): sub}
    for key in keys:
        words, op = key[skip:], hermes_api.COMMANDS[key]
        for i in range(1, len(words)):
            if words[:i] not in groups:
                group = groups[words[:i - 1]].add_parser(words[i - 1])
                groups[words[:i]] = group.add_subparsers(required=True, metavar="COMMAND")
        p = groups[words[:-1]].add_parser(words[-1], help=op["help"].replace("%", "%%"),
                                          description=f"{op['method']} {op['path']}")
        for name, where, kind, required, help in op["args"]:
            kw = {"help": help.replace("%", "%%")}
            if where == "path":
                p.add_argument(name, type=TYPES.get(kind), **kw)
                continue
            kw.update(dest=name, required=required)
            if kind == "bool":
                # argparse can't add a --no- form to a flag that already starts with one.
                if name.startswith("no_"):
                    kw.update(action="store_const", const=True)
                else:
                    kw["action"] = argparse.BooleanOptionalAction
            elif kind == "list":
                kw["action"] = "append"
            else:
                kw["type"] = TYPES.get(kind)
            p.add_argument("--" + name.replace("_", "-"), **kw)
        p.set_defaults(_run=lambda a, key=key: run(key, **vars(a)))


def parser():
    top = argparse.ArgumentParser(prog="hermes", description="Hermes on " + BASE)
    sub = top.add_subparsers(metavar="COMMAND")
    sub.add_parser("login", help="Sign in through the dashboard").set_defaults(_run=login)
    sub.add_parser("ticket", help="Print a TUI WebSocket ticket").set_defaults(_run=lambda a: ticket())
    keys = sorted(hermes_api.COMMANDS)
    add_commands(sub, [k for k in keys if k[0] != "kanban"])
    api = kanban.register(sub, run).add_parser("api", help="The kanban API's operations")
    add_commands(api.add_subparsers(required=True, metavar="COMMAND"), [k for k in keys if k[0] == "kanban"], skip=1)
    return top


def ticket():
    return call("POST", "/api/auth/ws-ticket")["ticket"]


def main(argv):
    if not argv or argv[0] not in {"-h", "--help", "login", "ticket", "kanban", *(k[0] for k in hermes_api.COMMANDS)}:
        # Hermes's pinned Node ignores the system store, where the step CA's root is.
        os.environ.update(NODE_EXTRA_CA_CERTS="/etc/ssl/certs/ca-certificates.crt", HERMES_HOME=str(STATE / "home"),
                          HERMES_TUI_GATEWAY_URL=f"wss://{urllib.parse.urlsplit(BASE).netloc}/api/ws?ticket={ticket()}")
        os.execv(os.environ["HERMES_REMOTE_TUI"], ["hermes", "--tui", *argv])
    args = parser().parse_args(argv)
    if (out := args._run(args)) is not None:
        if isinstance(out, bytes):
            sys.stdout.buffer.write(out)
        else:
            print(out if isinstance(out, str) else json.dumps(out, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main(sys.argv[1:])
