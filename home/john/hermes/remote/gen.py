"""OpenAPI spec (stdin) -> the remote CLI's command table, as a Python module (stdout).

Each /api operation becomes a command: its path's namespace and static words, then a verb. GET is
`list` when the path has a `/{param}` child, else `get`; POST is `create`, or the last word when it
is the path's only method on a leaf; PUT `set`, PATCH `patch`, DELETE `delete`. Arguments are
(name, where, kind, required, help) with `where` path, query, json or form.
"""

import json
import pprint
import sys

spec = json.load(sys.stdin)
schemas = spec["components"]["schemas"]
VERBS = {"get": "get", "post": "create", "put": "set", "patch": "patch", "delete": "delete"}
KINDS = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "array": "list"}


def resolve(s):
    while "$ref" in s:
        s = schemas[s["$ref"].rsplit("/", 1)[1]]
    return next((resolve(a) for a in s.get("anyOf", ()) if a.get("type") != "null"), s)


def kind(s):
    s = resolve(s)
    return "file" if "contentMediaType" in s else KINDS.get(s.get("type"), "json")


def arg(name, where, schema, required, help=""):
    return (name, where, kind(schema), required, " ".join((help or schema.get("description", "")).split()))


paths = {p: ops for p, ops in spec["paths"].items() if p.startswith("/api/")}
commands = {}
for path, ops in sorted(paths.items()):
    segs = path.removeprefix("/api/").removeprefix("plugins/").split("/")
    words = [s for s in segs if not s.startswith("{")]
    children = [p for p in paths if p.startswith(path + "/")]
    for method, op in sorted(ops.items()):
        if method not in VERBS:
            continue
        verb, group = VERBS[method], words
        if method == "get" and any("/" not in c[len(path) + 1:] and c[len(path) + 1] == "{" for c in children):
            verb = "list"
        if method == "post" and not children and set(ops) & set(VERBS) == {"post"}:
            verb, group = words[-1], words[:-1]
        args = [arg(p["name"], p["in"], p["schema"], p.get("required", False), p.get("description"))
                for p in op.get("parameters", ())]
        body = None
        for media, where in (("application/json", "json"), ("multipart/form-data", "form")):
            if content := op.get("requestBody", {}).get("content", {}).get(media):
                body, s = where, resolve(content["schema"])
                # Every route takes a `profile` query parameter; a body's own `profile` is the one it reads.
                args = [a for a in args if a[0] not in s["properties"]] + [arg(n, where, f, n in s.get("required", ())) for n, f in sorted(s["properties"].items())]
        key = (*group, verb)
        assert key not in commands, f"{key}: {commands.get(key, {}).get('path')} and {path}"
        assert len({a[0] for a in args}) == len(args), f"{key}: duplicate argument"
        commands[key] = {"method": method.upper(), "path": path, "body": body, "args": tuple(args),
                         "help": " ".join(op.get("summary", "").split())}

assert not any(k[:i] in commands for k in commands for i in range(1, len(k))), "a command is also a group"
print(f'"""Generated by gen.py from the Hermes OpenAPI spec; do not edit."""\n\nCOMMANDS = {pprint.pformat(commands, width=110)}')
